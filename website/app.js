// A small to-do list. Everything runs in the browser: there is no server,
// so tasks are kept in the browser's localStorage.

const STORAGE_KEY = "todo-tasks";

// Tasks that every visitor starts with. They are added once per browser;
// after that they can be ticked off or deleted like any other task.
// To add more starter tasks later, add them here and change STARTER_KEY
// (e.g. to "todo-starter-v2") so browsers pick up the new ones.
const STARTER_KEY = "todo-starter-v1";
const STARTER_TASKS = [
  "Learn German language",
  "Block date for Security+ exam",
  "Review plan for interview",
];

const form = document.getElementById("add-form");
const input = document.getElementById("new-task");
const list = document.getElementById("task-list");
const emptyMessage = document.getElementById("empty");
const count = document.getElementById("count");
const clearDone = document.getElementById("clear-done");
const filterButtons = document.querySelectorAll(".filters button");

let tasks = addStarterTasks(loadTasks());
let filter = "all";

function loadTasks() {
  try {
    const saved = JSON.parse(localStorage.getItem(STORAGE_KEY));
    return Array.isArray(saved) ? saved : [];
  } catch {
    return [];
  }
}

function addStarterTasks(current) {
  try {
    if (localStorage.getItem(STARTER_KEY)) return current;
    localStorage.setItem(STARTER_KEY, "added");
  } catch {
    // No storage available: just show the starter tasks for this visit.
  }
  const existing = new Set(current.map((task) => task.text));
  const missing = STARTER_TASKS.filter((text) => !existing.has(text));
  return [...current, ...missing.map((text) => ({ text, done: false }))];
}

function saveTasks() {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(tasks));
  } catch {
    // Storage can be unavailable (e.g. private windows); the app still works
    // until the page is closed.
  }
}

function render() {
  const visible = tasks.filter((task) => {
    if (filter === "active") return !task.done;
    if (filter === "done") return task.done;
    return true;
  });

  list.replaceChildren(...visible.map(renderTask));
  emptyMessage.hidden = visible.length > 0;

  const remaining = tasks.filter((task) => !task.done).length;
  count.textContent = `${remaining} ${remaining === 1 ? "task" : "tasks"} left`;
  clearDone.hidden = remaining === tasks.length;
}

function renderTask(task) {
  const item = document.createElement("li");
  if (task.done) item.classList.add("done");

  const label = document.createElement("label");
  const checkbox = document.createElement("input");
  checkbox.type = "checkbox";
  checkbox.checked = task.done;
  checkbox.addEventListener("change", () => {
    task.done = checkbox.checked;
    update();
  });

  const text = document.createElement("span");
  text.textContent = task.text;
  label.append(checkbox, text);

  const remove = document.createElement("button");
  remove.type = "button";
  remove.className = "remove";
  remove.textContent = "×";
  remove.setAttribute("aria-label", `Delete "${task.text}"`);
  remove.addEventListener("click", () => {
    tasks = tasks.filter((other) => other !== task);
    update();
  });

  item.append(label, remove);
  return item;
}

function update() {
  saveTasks();
  render();
}

form.addEventListener("submit", (event) => {
  event.preventDefault();
  const text = input.value.trim();
  if (!text) return;
  tasks.push({ text, done: false });
  input.value = "";
  update();
});

filterButtons.forEach((button) => {
  button.addEventListener("click", () => {
    filter = button.dataset.filter;
    filterButtons.forEach((other) => other.classList.toggle("active", other === button));
    render();
  });
});

clearDone.addEventListener("click", () => {
  tasks = tasks.filter((task) => !task.done);
  update();
});

update();

// config.json is generated by Terraform from the variables in variables.tf.
fetch("config.json")
  .then((response) => response.json())
  .then((config) => {
    document.getElementById("welcome").textContent = config.welcome_message;
    document.getElementById("app-info").textContent =
      `${config.environment} · v${config.version} · ${config.region}`;
  })
  .catch(() => {
    // The to-do list works fine without the config.
  });
